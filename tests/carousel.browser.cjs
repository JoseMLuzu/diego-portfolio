const { test, before, after } = require('node:test')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
let browser
const url = process.env.CAROUSEL_URL || 'http://127.0.0.1:5187'
const settle = page => page.waitForTimeout(1250)
const active = page => page.locator('.carousel-image[aria-current="true"]').getAttribute('data-image-index').then(Number)
const scale = (page, index) => page.locator(`[data-image-index="${index}"] img`).evaluate(e => new DOMMatrix(getComputedStyle(e).transform).a)
const metrics = page => page.evaluate(() => ({ step: (document.querySelector('.scroll-story').getBoundingClientRect().height - document.querySelector('.story-stage').getBoundingClientRect().height) / Number(document.querySelector('.scroll-story').dataset.lastScene), y: scrollY }))
async function open(options = {}, route = '') {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, ...options })
  await page.goto(`${url.split('#')[0]}#/${route}`)
  await page.locator('.story-stage').waitFor()
  await page.waitForTimeout(150)
  if (route === 'proyectos') await page.waitForFunction(() => document.querySelector('.gallery').getAttribute('aria-hidden') === 'false')
  return page
}
before(async () => { browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) }) })
after(async () => { await browser?.close() })

test('wheel drives the home and first cover together, snaps, and reverses back home', async () => {
  const page = await open()
  assert.equal(await page.locator('.carousel-image[aria-current]').count(), 0)
  const initialCover = await scale(page, 0)
  await page.mouse.move(720, 480)
  await page.mouse.wheel(0, 120)
  await page.waitForTimeout(65)
  const homeScale = await page.locator('.story-home').evaluate(e => new DOMMatrix(getComputedStyle(e).transform).a)
  assert.ok(homeScale < 0.99 && homeScale > 0.6)
  assert.ok(await scale(page, 0) > initialCover)
  assert.ok(await page.evaluate(() => scrollY) > 0)
  await page.mouse.wheel(0, 120)
  await settle(page)
  assert.equal(await active(page), 0)
  assert.ok(Math.abs(await scale(page, 0) - 1) < 0.002)
  await page.mouse.wheel(0, -300)
  await settle(page)
  assert.ok(await page.evaluate(() => scrollY) < 1)
  assert.equal(await page.locator('.carousel-image[aria-current]').count(), 0)
  await page.close()
})

test('a partial drag still scales continuously, then settles on the adjacent scene', async () => {
  const page = await open({}, 'proyectos')
  const image = await page.locator('[data-image-index="0"]').boundingBox()
  const x = image.x + image.width / 2, y = image.y + image.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x, y - 80, { steps: 8 })
  assert.equal(await active(page), 0)
  assert.ok(await scale(page, 0) < 0.95)
  assert.ok(await scale(page, 1) > 0.25)
  await page.mouse.up()
  await settle(page)
  assert.equal(await active(page), 1)
  assert.ok(Math.abs(await scale(page, 1) - 1) < 0.001)
  const current = await metrics(page)
  assert.ok(Math.abs(current.y - current.step * 2) < 1)
  await page.close()
})

