test('a short wheel gesture advances once and trackpad momentum cannot strand or skip scenes', async () => {
  const page = await open()
  await page.mouse.move(720, 480)
  await page.mouse.wheel(0, 20)
  for (let i = 0; i < 18; i++) { await page.mouse.wheel(0, 4); await page.waitForTimeout(16) }
  await settle(page)
  assert.equal(await active(page), 0)
  const first = await metrics(page)
  assert.ok(Math.abs(first.y - first.step) < 1)
  await page.mouse.wheel(0, -20)
  for (let i = 0; i < 12; i++) { await page.mouse.wheel(0, -3); await page.waitForTimeout(16) }
  await settle(page)
  assert.ok(await page.evaluate(() => scrollY) < 1)
  await page.close()
})

test('a 24px touch swipe always completes the next or previous scene', async () => {
  const page = await open({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }, 'proyectos')
  const cdp = await page.context().newCDPSession(page)
  const swipe = async distance => {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 195, y: 450 }] })
    for (let i = 1; i <= 4; i++) {
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 195, y: 450 - distance * i / 4 }] })
      await page.waitForTimeout(20)
    }
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await settle(page)
  }
  await swipe(24)
  assert.equal(await active(page), 1)
  let current = await metrics(page)
  assert.ok(Math.abs(current.y - current.step * 2) < 1)
  await swipe(-24)
  assert.equal(await active(page), 0)
  current = await metrics(page)
  assert.ok(Math.abs(current.y - current.step) < 1)
  await page.close()
})

