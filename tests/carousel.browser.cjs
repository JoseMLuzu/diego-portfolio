test('mobile swipes move the same timeline, and thumbnail taps advance it', async () => {
  const page = await open({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
  const cdp = await page.context().newCDPSession(page)
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
  await touch('touchStart', 195, 650)
  for (let y = 630; y >= 180; y -= 25) { await touch('touchMove', 195, y); await page.waitForTimeout(16) }
  await page.waitForTimeout(130)
  await touch('touchEnd')
  await settle(page)
  const index = await active(page)
  assert.equal(index, 0, 'A long swipe must advance exactly one scene')
  assert.ok(Math.abs(await scale(page, index) - 1) < 0.002)
  assert.ok(await page.evaluate(() => scrollY) > 0)
  const next = Math.min(8, index + 1)
  await page.locator(`[data-image-index="${next}"]`).tap()
  await settle(page)
  assert.equal(await active(page), next)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.close()
})

